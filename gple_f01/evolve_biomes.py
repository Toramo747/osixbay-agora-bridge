"""Bounded evolutionary proposal optimizer for synthetic F01 environments.

Searches candidate parameter combinations, not actual biomes nor adaptations of F01.
Original simulator stays untouched. Deterministic seed, no internet/LLMs.
"""
import argparse
import hashlib
import json
import random
import statistics
from pathlib import Path
from biome_search import VARIANTS, load_f01, run_trial, rank_candidate

def normalized_mix(values):
    total=sum(values)
    return [round(v/total,6) for v in values]

def mutate(parent,rng,index):
    mix=normalized_mix([max(0.05,x+rng.uniform(-0.18,0.18)) for x in parent["biome_mix"]])
    return {"id":f"evo_{index:03d}","label":"Hypothesis generated by deterministic search",
            "biome_mix":mix,
            "food_capacity":round(max(1.0,min(6.0,parent["food_capacity"]+rng.uniform(-0.7,0.7))),4),
            "regrowth":round(max(0.0,min(0.35,parent["regrowth"]+rng.uniform(-0.06,0.06))),4),
            "hazard":round(max(0.0,min(0.65,parent["hazard"]+rng.uniform(-0.09,0.09))),4)}

def evolve(original_sim,seed=2026,generations=3,population=6,ticks=100,
           trial_seeds=(11,23,37)):
    if not 1<=generations<=20 or not 2<=population<=30 or not 1<=ticks<=10000:
        raise ValueError("budget exceeded")
    if not trial_seeds or len(trial_seeds)>30:raise ValueError("invalid trials")
    rng=random.Random(seed)
    f01=load_f01(original_sim)
    parents=[dict(v) for v in VARIANTS[:population]]
    while len(parents)<population:
        parents.append(mutate(parents[-1],rng,len(parents)))
    generations_out=[]
    serial=100
    for generation in range(generations):
        evaluations=[]
        for candidate in parents:
            results=[run_trial(f01,candidate,s,ticks) for s in trial_seeds]
            score,extinction,cap_hit=rank_candidate(results)
            evaluations.append({"candidate":candidate,"screening_score":score,
                                "extinction_rate":extinction,"cap_hit_rate":cap_hit,
                                "mean_survivors":round(statistics.mean(t["survivors"] for t in results),3)})
        evaluations.sort(key=lambda x:(-x["screening_score"],x["candidate"]["id"]))
        generations_out.append({"generation":generation,"candidates":evaluations})
        if generation+1<generations:
            elite=[entry["candidate"] for entry in evaluations[:max(2,population//3)]]
            parents=[dict(v) for v in elite]
            while len(parents)<population:
                parents.append(mutate(rng.choice(elite),rng,serial))
                serial+=1
    data={"schema":"osixbay.gple.f01.generated-biome-hypotheses.v1",
          "status":"synthetic_selection_not_real_biome_discovery",
          "seed":seed,"trial_seeds":list(trial_seeds),"ticks_per_trial":ticks,
          "generations":generations_out,
          "top_proposal":generations_out[-1]["candidates"][0]["candidate"],
          "caveats":["Original F01 has global food regrowth, so biome mix is descriptive only",
                     "No intrinsic water, climate or substrate biology in this baseline",
                     "Selection heuristic can reward simulator weaknesses and MUST be audited",
                     "These parameters are not canonical or an environmental world export",
                     "No claim of F01 evolution or independent AI-agent cognition"]}
    raw=json.dumps(data,sort_keys=True,separators=(",",":")).encode()
    data["replay_digest_sha256"]=hashlib.sha256(raw).hexdigest()
    return data

if __name__=="__main__":
    ap=argparse.ArgumentParser()
    ap.add_argument("--original",default="genesis/fauna01/sim.py")
    ap.add_argument("--seed",type=int,default=2026)
    ap.add_argument("--generations",type=int,default=3)
    ap.add_argument("--out",default="f01-generated-biome-hypotheses.json")
    a=ap.parse_args()
    result=evolve(a.original,seed=a.seed,generations=a.generations)
    Path(a.out).parent.mkdir(parents=True,exist_ok=True)
    Path(a.out).write_text(json.dumps(result,indent=2,sort_keys=True)+"\n")
    print(json.dumps({"generations":len(result["generations"]),
                      "top_id":result["top_proposal"]["id"],
                      "digest":result["replay_digest_sha256"]}))
